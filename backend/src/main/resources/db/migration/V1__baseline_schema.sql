        ), subvention_calculee AS (
         SELECT ic.user_id,
            ic.order_date,
            ic.item_id,
            ic.subtotal,
            ic.restaurant_name,
            ic.max_subtotal,
            ic.rn,
            ic.cumul,
            ic.cumul_precedent,
            ip.item_principal_id,
            us.subsidy_cap,
                CASE
                    WHEN (ic.max_subtotal >= (us.subsidy_cap)::double precision) THEN (
                    CASE
                        WHEN (ic.item_id = ip.item_principal_id) THEN us.subsidy_cap
                        ELSE 0
                    END)::double precision
                    ELSE
                    CASE
                        WHEN (ic.cumul <= (us.subsidy_cap)::double precision) THEN ic.subtotal
                        WHEN (ic.cumul_precedent < (us.subsidy_cap)::double precision) THEN ((us.subsidy_cap)::double precision - ic.cumul_precedent)
                        ELSE (0)::double precision
                    END
                END AS subsidy_amount
           FROM ((items_avec_cumul_prec ic
             JOIN item_principal ip ON (((ic.user_id = ip.user_id) AND (ic.order_date = ip.order_date))))
             JOIN user_subsidy us ON ((ic.user_id = us.user_id)))
        ), jours_commandes AS (
         SELECT (date_trunc('week'::text, (items_par_jour.order_date)::timestamp with time zone))::date AS semaine_debut,
            items_par_jour.restaurant_name,
            count(DISTINCT items_par_jour.order_date) AS nb_jours_livraison
           FROM items_par_jour
          GROUP BY (date_trunc('week'::text, (items_par_jour.order_date)::timestamp with time zone)), items_par_jour.restaurant_name
        ), recap_semaine AS (
         SELECT (date_trunc('week'::text, (sc.order_date)::timestamp with time zone))::date AS semaine_debut,
            sc.restaurant_name,
            count(sc.item_id) AS nbre_commandes,
            count(
                CASE
                    WHEN (sc.subsidy_amount > (0)::double precision) THEN 1
                    ELSE NULL::integer
                END) AS nbre_commandes_subventionnees,
            sum(sc.subtotal) AS sous_total,
            sum(sc.subsidy_amount) AS total_subvention
           FROM subvention_calculee sc
          GROUP BY (date_trunc('week'::text, (sc.order_date)::timestamp with time zone)), sc.restaurant_name
        )
 SELECT ((rs.semaine_debut || ' - '::text) || ((rs.semaine_debut + '4 days'::interval))::date) AS periode,
    rs.restaurant_name,
    rs.nbre_commandes,
    rs.nbre_commandes_subventionnees,
    rs.sous_total,
    rs.total_subvention,
    (rs.sous_total - rs.total_subvention) AS total_a_payer,
        CASE
            WHEN ((rs.restaurant_name)::text = 'JOLOF'::text) THEN (0)::bigint
            ELSE (jc.nb_jours_livraison * 1000)
        END AS total_livraison_semaine
   FROM (recap_semaine rs
     JOIN jours_commandes jc ON (((rs.semaine_debut = jc.semaine_debut) AND ((rs.restaurant_name)::text = (jc.restaurant_name)::text))))
  ORDER BY rs.semaine_debut DESC, rs.restaurant_name;


--
-- Name: view_rodra; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.view_rodra AS
 WITH user_subsidy AS (
         SELECT users.id AS user_id,
                CASE
                    WHEN COALESCE(users.is_intern, false) THEN 2000
                    ELSE 1000
                END AS subsidy_cap
           FROM public.users
        ), items_par_jour AS (
         SELECT o_1.user_id,
            o_1.order_date,
            oi_1.id AS item_id,
            oi_1.subtotal,
            r_1.restaurant_name
           FROM ((public.orders o_1
             JOIN public.order_items oi_1 ON ((oi_1.order_id = o_1.id)))
             JOIN public.restaurant r_1 ON ((oi_1.restaurant_id = r_1.id)))
          WHERE ((o_1.status)::text = 'CONFIRMED'::text)
        ), max_prix AS (
         SELECT items_par_jour.user_id,
            items_par_jour.order_date,
            max(items_par_jour.subtotal) AS max_subtotal
           FROM items_par_jour
          GROUP BY items_par_jour.user_id, items_par_jour.order_date
        ), items_ordonnes AS (
         SELECT i.user_id,
            i.order_date,
            i.item_id,
            i.subtotal,
            i.restaurant_name,
            m_1.max_subtotal,
            row_number() OVER (PARTITION BY i.user_id, i.order_date ORDER BY i.subtotal, i.item_id) AS rn,
            sum(i.subtotal) OVER (PARTITION BY i.user_id, i.order_date ORDER BY i.subtotal, i.item_id ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS cumul
           FROM (items_par_jour i
             JOIN max_prix m_1 ON (((i.user_id = m_1.user_id) AND (i.order_date = m_1.order_date))))
        ), items_avec_cumul_prec AS (
         SELECT items_ordonnes.user_id,
            items_ordonnes.order_date,
            items_ordonnes.item_id,
            items_ordonnes.subtotal,
            items_ordonnes.restaurant_name,
            items_ordonnes.max_subtotal,
            items_ordonnes.rn,
            items_ordonnes.cumul,
            COALESCE(lag(items_ordonnes.cumul) OVER (PARTITION BY items_ordonnes.user_id, items_ordonnes.order_date ORDER BY items_ordonnes.rn), (0)::double precision) AS cumul_precedent
           FROM items_ordonnes
        ), item_principal AS (
         SELECT DISTINCT ON (items_par_jour.user_id, items_par_jour.order_date) items_par_jour.user_id,
            items_par_jour.order_date,
            items_par_jour.item_id AS item_principal_id
           FROM items_par_jour
          ORDER BY items_par_jour.user_id, items_par_jour.order_date, items_par_jour.subtotal DESC, items_par_jour.item_id
        ), subvention_calculee AS (
         SELECT ic.user_id,
            ic.order_date,
            ic.item_id,
            ic.subtotal,
            ic.restaurant_name,
            ic.max_subtotal,
            ic.rn,
            ic.cumul,
            ic.cumul_precedent,
            ip.item_principal_id,
            us.subsidy_cap,
                CASE
                    WHEN (ic.max_subtotal >= (us.subsidy_cap)::double precision) THEN (
                    CASE
                        WHEN (ic.item_id = ip.item_principal_id) THEN us.subsidy_cap
                        ELSE 0
                    END)::double precision
                    ELSE
                    CASE
                        WHEN (ic.cumul <= (us.subsidy_cap)::double precision) THEN ic.subtotal
                        WHEN (ic.cumul_precedent < (us.subsidy_cap)::double precision) THEN ((us.subsidy_cap)::double precision - ic.cumul_precedent)
                        ELSE (0)::double precision
                    END
                END AS subsidy_amount
           FROM ((items_avec_cumul_prec ic
             JOIN item_principal ip ON (((ic.user_id = ip.user_id) AND (ic.order_date = ip.order_date))))
             JOIN user_subsidy us ON ((ic.user_id = us.user_id)))
        ), daily_clients_rodra AS (
         SELECT o_1.order_date,
            count(DISTINCT o_1.user_id) AS nb_clients
           FROM ((public.orders o_1
             JOIN public.order_items oi_1 ON ((oi_1.order_id = o_1.id)))
             JOIN public.restaurant r_1 ON ((oi_1.restaurant_id = r_1.id)))
          WHERE (((o_1.status)::text = 'CONFIRMED'::text) AND ((r_1.restaurant_name)::text = 'RODRA'::text))
          GROUP BY o_1.order_date
        )
 SELECT o.order_date,
    u.first_name,
    u.last_name,
    m.meal_name,
    oi.subtotal,
    sc.subsidy_amount,
    GREATEST((oi.subtotal - sc.subsidy_amount), (0)::double precision) AS amount_after_subsidy,
    round((1000.0 / (dc.nb_clients)::numeric), 0) AS delivery_fee_share,
    (GREATEST((oi.subtotal - sc.subsidy_amount), (0)::double precision) + (round((1000.0 / (dc.nb_clients)::numeric), 0))::double precision) AS total_amount
   FROM ((((((public.orders o
     JOIN public.users u ON ((o.user_id = u.id)))
     JOIN public.order_items oi ON ((oi.order_id = o.id)))
     JOIN public.restaurant r ON ((oi.restaurant_id = r.id)))
     JOIN public.meals m ON ((oi.meal_id = m.id)))
     JOIN subvention_calculee sc ON ((sc.item_id = oi.id)))
     JOIN daily_clients_rodra dc ON ((o.order_date = dc.order_date)))
  WHERE (((o.status)::text = 'CONFIRMED'::text) AND ((r.restaurant_name)::text = 'RODRA'::text))
  ORDER BY o.order_date DESC, u.last_name, oi.subtotal DESC;


